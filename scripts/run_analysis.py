"""Regenerate every figure and the results summary from the data in data/.

    python scripts/run_analysis.py

Writes figures/*.png, results/summary.json and results/summary.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from nyc_air import analysis, data, plots  # noqa: E402

FIG_DIR = ROOT / "figures"
RESULTS_DIR = ROOT / "results"


def headline_numbers(r: dict) -> dict:
    """The numbers quoted in the README, rounded the way they are quoted."""
    t, s, src, b = r["trend"], r["smoke"], r["sources"], r["burden"]
    table = src["table"].set_index(["pollutant", "source"])
    return {
        "pm25_annual_first": round(float(t["pm25_first"]), 1),
        "pm25_annual_low": round(float(t["pm25_low"]), 1),
        "pm25_low_year": t["pm25_low_year"],
        "pm25_annual_last": round(float(t["pm25_last"]), 1),
        "last_year": t["last_year"],
        "pm25_drop_to_low_pct": round(float(t["pm25_drop_to_low_pct"])),
        "pm25_drop_to_last_pct": round(float(t["pm25_drop_to_last_pct"])),
        "no2_drop_pct": round(float(t["no2_drop_pct"])),
        "ozone_summer_2010": round(float(t["ozone_2010"]), 1),
        "ozone_summer_last": round(float(t["ozone_last"]), 1),
        "summer_2023_actual": round(float(s["actual"]), 1),
        "summer_2023_expected": round(float(s["expected"]), 1),
        "summer_2023_above_trend_pct": round(float(s["above_trend_pct"])),
        "summer_2023_highest_since": s["highest_summer_since"],
        "neighborhoods_worse_2023": f"{s['n_rose']} of {s['n_neighborhoods']}",
        "neighborhood_change_range_pct": [round(float(s["change_min"])),
                                          round(float(s["change_max"]))],
        "neighborhood_change_median_pct": round(float(s["change_median"])),
        "r_pm25_traffic": round(float(table.loc[("PM2.5", "Traffic (all vehicles)"), "r"]), 2),
        "r_pm25_trucks": round(float(table.loc[("PM2.5", "Traffic (trucks)"), "r"]), 2),
        "r_pm25_boilers": round(float(table.loc[("PM2.5", "Building boilers (PM2.5)"), "r"]), 2),
        "r_traffic_vs_boilers": round(float(src["traffic_vs_boilers_r"]), 2),
        "exposure_ratio": round(float(b["exposure_ratio"]), 1),
        "child_asthma_ed_ratio": round(float(b["child_ed_ratio"])),
        "r_pm25_vs_child_asthma_ed": round(float(b["pm_vs_child_ed"]["r"]), 2),
        "p_pm25_vs_child_asthma_ed": round(float(b["pm_vs_child_ed"]["p"]), 2),
        "highest_child_asthma_ed": b["top_child_ed"].index[:3].tolist(),
    }


def summary_markdown(r: dict, h: dict) -> str:
    src = r["sources"]["table"].copy()
    src["r"] = src["r"].map("{:.2f}".format)
    src["spearman"] = src["spearman"].map("{:.2f}".format)
    src["p"] = src["p"].map("{:.1e}".format)
    top = r["burden"]["top_child_ed"].round(1)
    lines = [
        "# Results summary",
        "",
        "Generated by `scripts/run_analysis.py`. Do not edit by hand.",
        "",
        "## Headline numbers",
        "",
        "```json",
        json.dumps(h, indent=2),
        "```",
        "",
        f"## Source correlations ({r['sources']['year']}, 42 neighborhoods)",
        "",
        src.to_markdown(index=False),
        "",
        "## Highest PM2.5-caused child asthma ER visit rates (2017–2019)",
        "",
        top.to_markdown(),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    FIG_DIR.mkdir(exist_ok=True)
    RESULTS_DIR.mkdir(exist_ok=True)

    df = data.load_air_quality()
    hoods = data.load_neighborhoods()
    ids = data.neighborhood_ids(df)
    r = analysis.run_all(df)

    plots.use_style()
    figures = {
        "1_pm25_trend.png": plots.trend_chart(r["trend"], r["smoke"]),
        "2_smoke_2023_map.png": plots.smoke_map(r["smoke"], hoods, ids),
        "3_sources.png": plots.sources_chart(r["sources"]),
        "4_exposure_vs_harm.png": plots.burden_maps(r["burden"], hoods, ids),
    }
    for name, fig in figures.items():
        fig.savefig(FIG_DIR / name)
        plt.close(fig)
        print(f"wrote figures/{name}")

    h = headline_numbers(r)
    (RESULTS_DIR / "summary.json").write_text(json.dumps(h, indent=2) + "\n")
    (RESULTS_DIR / "summary.md").write_text(summary_markdown(r, h))
    print("wrote results/summary.json and results/summary.md")
    print(json.dumps(h, indent=2))


if __name__ == "__main__":
    main()
